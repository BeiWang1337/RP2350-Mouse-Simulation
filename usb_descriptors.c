#define SIM_TUD_HID_INOUT_DESCRIPTOR(_itfnum, _stridx, _boot_protocol, _report_desc_len, _epout, _epin, _ep_size, _ep_interval) \
  0x09, TUSB_DESC_INTERFACE, _itfnum, 0, 2, TUSB_CLASS_HID, 0x00, _boot_protocol, _stridx, \
